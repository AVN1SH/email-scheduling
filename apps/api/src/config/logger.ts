import pino, { type DestinationStream, type LoggerOptions } from "pino";

export function createLogger(
  service: string,
  level = "info",
  destination?: DestinationStream,
) {
  const options: LoggerOptions = {
    level,
    base: { service },
    redact: {
      paths: [
        "password",
        "token",
        "secret",
        "connectionString",
        "DATABASE_URL",
        "DIRECT_URL",
        "REDIS_URL",
        "SESSION_SECRET",
        "GOOGLE_CLIENT_SECRET",
        "SLACK_CLIENT_SECRET",
        "*.SLACK_CLIENT_SECRET",
        "webhookEncrypted",
        "*.webhookEncrypted",
        "webhookUrl",
        "*.webhookUrl",
        "access_token",
        "*.access_token",
        "incoming_webhook.url",
        "*.incoming_webhook.url",
        "ELASTICSEARCH_API_KEY",
        "*.ELASTICSEARCH_API_KEY",
        "apiKey",
        "*.apiKey",
        "ELASTIC_PASSWORD",
        "CREDENTIAL_ENCRYPTION_KEY",
        "*.CREDENTIAL_ENCRYPTION_KEY",
        "smtpPassword",
        "*.smtpPassword",
        "credentialsEncrypted",
        "*.credentialsEncrypted",
        "passwordHash",
        "*.passwordHash",
        "csrfToken",
        "*.csrfToken",
        "code",
        "*.code",
        "*.password",
        "*.token",
        "*.secret",
        "*.connectionString",
        "req.headers.authorization",
        "req.headers.cookie",
        'res.headers["set-cookie"]',
      ],
      censor: "[REDACTED]",
    },
  };
  return destination ? pino(options, destination) : pino(options);
}
